create table if not exists public.users (
  username text primary key,
  salt text not null,
  "passwordHash" text not null,
  "sessionHash" text,
  "sessionCreatedAt" timestamptz,
  history jsonb not null default '[]'::jsonb,
  configs jsonb not null default '{}'::jsonb,
  settings jsonb not null default '{}'::jsonb,
  "createdAt" timestamptz not null default now()
);

create index if not exists users_session_hash_idx
  on public.users ("sessionHash")
  where "sessionHash" is not null;

alter table public.users
  add column if not exists ai jsonb not null default '{"chats":[],"goals":[],"drafts":[],"tokenUsage":{"input":0,"output":0,"cached":0}}'::jsonb;

create table if not exists public.public_configs (
  id bigint generated by default as identity primary key,
  page text not null,
  username text not null,
  "configName" text,
  config jsonb,
  slug text,
  portfolio jsonb,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create unique index if not exists public_configs_named_config_idx
  on public.public_configs (page, username, "configName")
  where "configName" is not null;

create unique index if not exists public_configs_portfolio_slug_idx
  on public.public_configs (page, slug)
  where slug is not null;

create index if not exists public_configs_page_created_idx
  on public.public_configs (page, "createdAt" desc);
